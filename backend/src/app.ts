import express from 'express';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { authenticate } from './middlewares/authenticate.js';
import { errorHandler } from './middlewares/errorHandler.js';
import authRoutes from './routes/authRoutes.js';
import { crudRoutes } from './routes/crudRoutes.js';
import motorcycleRoutes from './routes/motorcycleRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
import userRoutes from './routes/userRoutes.js';
import dashboardRoutes from './routes/dashboardRoutes.js';
import serviceRoutes from './routes/serviceRoutes.js';
import { clientesRepository } from './repositories/Repositories.js';
import { CrudController } from './controllers/CrudController.js';
import { CrudService } from './services/CrudService.js';
import { clientSchema } from './validators/schemas.js';
import { AppError } from './errors/AppError.js';

const app = express();
app.disable('x-powered-by');
app.set('trust proxy', 1);
app.use(helmet());
app.use(express.json({ limit: '1mb' }));
app.use(rateLimit({ windowMs: 60_000, limit: 120, standardHeaders: true, legacyHeaders: false }));
app.get('/api/health', (_request, response) => response.json({ status: 'ok' }));
app.use('/api/auth', authRoutes);
app.use('/api/users', userRoutes);
app.use('/api/dashboard', authenticate, dashboardRoutes);
app.use('/api/clientes', authenticate, crudRoutes(new CrudController(new CrudService(clientesRepository, 'clientes'), clientSchema, 'clientes')));
app.use('/api/motocicletas', authenticate, motorcycleRoutes);
app.use('/api/servicos', authenticate, serviceRoutes);
app.use('/api/ordens-servico', authenticate, orderRoutes);
app.use((_request, _response, next) => next(new AppError(404, 'Rota não encontrada.', 'ROUTE_NOT_FOUND')));
app.use(errorHandler);
export default app;
